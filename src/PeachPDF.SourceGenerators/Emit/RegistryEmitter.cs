            sb.AppendLine("        private static readonly FrozenDictionary<string, Func<CssValueParser, string, bool>> _supportsValidators =");
            sb.AppendLine("            new Dictionary<string, Func<CssValueParser, string, bool>>(StringComparer.Ordinal)");
            sb.AppendLine("            {");
            foreach (var entry in entries)
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = Supports_{PascalCase(entry.Name)},");
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.Ordinal);");
        }

        private static void EmitInheritedProperties(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        internal static readonly FrozenSet<string> InheritedProperties =");
            sb.AppendLine("            new HashSet<string>(StringComparer.OrdinalIgnoreCase)");
            sb.AppendLine("            {");
            foreach (var entry in entries.Where(e => e.Inherited))
                sb.AppendLine($"                {StringLiteral(entry.Name)},");
            sb.AppendLine("            }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);");
        }

        private static void EmitInitialValues(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        internal static readonly FrozenDictionary<string, string?> InitialValues =");
            sb.AppendLine("            new Dictionary<string, string?>(StringComparer.OrdinalIgnoreCase)");
            sb.AppendLine("            {");
            foreach (var entry in entries.Where(e => e.InitialValueKind != InitialValueKind.None))
            {
                var valueExpr = entry.InitialValueKind == InitialValueKind.Literal
                    ? StringLiteral(entry.InitialValueText!)
                    : entry.InitialValueText; // Expression — spliced verbatim, e.g. CssConstants.DefaultFont
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = {valueExpr},");
            }
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);");
        }

        private static void EmitSnapshotPropertyNames(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        internal static readonly string[] SnapshotPropertyNames =");
            sb.AppendLine("        {");
            foreach (var entry in entries.Where(e => e.Html!.Snapshot))
                sb.AppendLine($"            {StringLiteral(entry.Name)},");
            sb.AppendLine("        };");
        }

        private static void EmitLogicalProperties(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        internal static readonly FrozenDictionary<string, (string Group, string Axis, string Side)> LogicalProperties =");
            sb.AppendLine("            new Dictionary<string, (string Group, string Axis, string Side)>(StringComparer.Ordinal)");
            sb.AppendLine("            {");
            foreach (var entry in entries.Where(e => e.Category == PropertyCategory.Logical))
            {
                var t = entry.ResolvesTo;
                var tuple = t is null ? "(\"\", \"\", \"\")" : $"({StringLiteral(t.Group)}, {StringLiteral(t.Axis)}, {StringLiteral(t.Side)})";
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = {tuple},");
            }
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.Ordinal);");
        }

        public static string EmitSvgRegistry(IReadOnlyList<PropertyEntry> entries)
        {
            var svgEntries = entries.Where(e => e.Svg is not null && e.Svg.ApplyIn == SvgApplyIn.Common).ToList();
            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Generated by PeachPDF.SourceGenerators from css-properties.json. Do not edit by hand —");
            sb.AppendLine("// edit the JSON entry and rebuild. See CLAUDE.md's generator section.");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Frozen;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using PeachPDF.Html.Adapters;");
            sb.AppendLine("using PeachPDF.Html.Adapters.Entities;");
            sb.AppendLine();
            sb.AppendLine("namespace PeachPDF.Svg");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>Everything a generated SVG customSetter/default setter needs beyond the raw value — see CLAUDE.md's generator section.</summary>");
            sb.AppendLine("    internal readonly struct SvgPropertyContext");
            sb.AppendLine("    {");
            sb.AppendLine("        public RAdapter Adapter { get; }");
            sb.AppendLine("        public RColor ContextColor { get; }");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>The current viewport's diagonal (per the SVG percentage-length formula) — needed to resolve a percentage stroke-width/dashoffset/dasharray entry; null where no viewport is established yet.</summary>");
            sb.AppendLine("        public double? ViewportDiagonal { get; }");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>Reclassifies a url()-referencing SvgPaint as a gradient vs. pattern reference against the current document's id registries — see SvgTreeBuilder.ResolveUrlPaintKind. The nominal @supports context uses the identity function.</summary>");
            sb.AppendLine("        public Func<SvgPaint, SvgPaint> ResolveUrlPaintKind { get; }");
            sb.AppendLine();
            sb.AppendLine("        public SvgPropertyContext(RAdapter adapter, RColor contextColor, double? viewportDiagonal, Func<SvgPaint, SvgPaint> resolveUrlPaintKind)");
            sb.AppendLine("        {");
            sb.AppendLine("            Adapter = adapter;");
            sb.AppendLine("            ContextColor = contextColor;");
            sb.AppendLine("            ViewportDiagonal = viewportDiagonal;");
            sb.AppendLine("            ResolveUrlPaintKind = resolveUrlPaintKind;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    internal static partial class SvgPropertyRegistry");
            sb.AppendLine("    {");

            foreach (var entry in svgEntries)
                EmitSvgEntryMethods(sb, entry);

            EmitSvgSetterDictionary(sb, svgEntries);
            EmitSvgValidatorDictionary(sb, svgEntries);
            EmitSvgInheritedProperties(sb, svgEntries);
            EmitSvgInitialValues(sb, svgEntries);

            sb.AppendLine();
            sb.AppendLine("        internal static bool IsKnownProperty(string name) => _setters.ContainsKey(name);");
            sb.AppendLine();
            sb.AppendLine("        internal static bool TrySet(SvgElement element, string name, string value, in SvgPropertyContext ctx) =>");
            sb.AppendLine("            _setters.TryGetValue(name, out var setter) && setter(element, ctx, value);");
            sb.AppendLine();
            sb.AppendLine("        internal static string? GetInitialValue(string name) => InitialValues.TryGetValue(name, out var v) ? v : null;");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>Validation only, with a nominal default context — the @supports render-layer oracle for SVG.</summary>");
            sb.AppendLine("        internal static bool SupportsDeclaration(string name, string value)");
            sb.AppendLine("        {");
            sb.AppendLine("            var ctx = new SvgPropertyContext(new global::PeachPDF.Adapters.PdfSharpAdapter(), RColor.Black, null, static p => p);");
            sb.AppendLine("            return _validators.TryGetValue(name, out var validator) && validator(ctx, value);");
            sb.AppendLine("        }");

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static void EmitSvgEntryMethods(StringBuilder sb, PropertyEntry entry)
        {
            var id = PascalCase(entry.Name);
            var svg = entry.Svg!;

            sb.AppendLine();
            sb.AppendLine($"        // \"{entry.Name}\"");

            var validatorExpr = svg.CustomValidator is not null
                ? Substitute(svg.CustomValidator, value: "value", ctx: "ctx")
                : ValidatorExpressionBuilder.BuildSvg(entry);

            sb.AppendLine($"        private static bool Validate_{id}(in SvgPropertyContext ctx, string value) => {validatorExpr};");

            sb.AppendLine($"        private static bool Set_{id}(SvgElement element, in SvgPropertyContext ctx, string value)");
            sb.AppendLine("        {");
            foreach (var line in BuildSvgSetterBody(entry, id).Split('\n'))
                sb.AppendLine($"            {line}");
            sb.AppendLine("        }");
        }

        private static string BuildSvgSetterBody(PropertyEntry entry, string id)
        {
            var svg = entry.Svg!;

            if (svg.CustomSetter is not null)
            {
                var custom = Substitute(svg.CustomSetter, value: "value", element: "element", ctx: "ctx");
                return $"if (!Validate_{id}(in ctx, value)) return false;\n{custom}\nreturn true;";
            }

            var kind = entry.CssDataTypes.Count == 1
                ? entry.CssDataTypes[0].Kind
                : throw new NotSupportedException($"\"{entry.Name}\" has no customSetter and its cssDataType is a union — a default SVG setter needs exactly one data type.");

            return kind switch
            {
                DataTypeKind.SvgPaint =>
                    "if (!global::PeachPDF.Svg.SvgValueParsers.TryParsePaint(value, ctx.Adapter, ctx.ContextColor, out var parsed)) return false;\n" +
                    $"element.{svg.PropertyPath} = ctx.ResolveUrlPaintKind(parsed);\nreturn true;",
                DataTypeKind.SvgOpacity =>
                    "if (!global::PeachPDF.Svg.SvgValueParsers.TryParseOpacity(value, out var parsed)) return false;\n" +
                    $"element.{svg.PropertyPath} = parsed;\nreturn true;",
                DataTypeKind.SvgLength =>
                    "var parsed = global::PeachPDF.Svg.SvgValueParsers.ParseLength(value, ctx.ViewportDiagonal);\n" +
                    $"if (parsed is null) return false;\nelement.{svg.PropertyPath} = parsed.Value;\nreturn true;",
                DataTypeKind.SvgLengthList =>
                    "var parsed = global::PeachPDF.Svg.SvgValueParsers.ParseDashArray(value, ctx.ViewportDiagonal);\n" +
                    $"if (parsed is null) return false;\nelement.{svg.PropertyPath} = parsed;\nreturn true;",
                DataTypeKind.CssOm => $"element.{svg.PropertyPath} = value;\nreturn true;",
                _ => throw new NotSupportedException(
                    $"DataTypeKind.{kind} has no default SVG setter and \"{entry.Name}\" declares no customSetter."),
            };
        }

        private static void EmitSvgSetterDictionary(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        private static readonly FrozenDictionary<string, Func<SvgElement, SvgPropertyContext, string, bool>> _setters =");
            sb.AppendLine("            new Dictionary<string, Func<SvgElement, SvgPropertyContext, string, bool>>(StringComparer.Ordinal)");
            sb.AppendLine("            {");
            foreach (var entry in entries)
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = (element, ctx, value) => Set_{PascalCase(entry.Name)}(element, in ctx, value),");
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.Ordinal);");
        }

        private static void EmitSvgValidatorDictionary(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        private static readonly FrozenDictionary<string, Func<SvgPropertyContext, string, bool>> _validators =");
            sb.AppendLine("            new Dictionary<string, Func<SvgPropertyContext, string, bool>>(StringComparer.Ordinal)");
            sb.AppendLine("            {");
            foreach (var entry in entries)
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = (ctx, value) => Validate_{PascalCase(entry.Name)}(in ctx, value),");
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.Ordinal);");
        }

        private static void EmitSvgInheritedProperties(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        internal static readonly FrozenSet<string> InheritedProperties =");
            sb.AppendLine("            new HashSet<string>(StringComparer.OrdinalIgnoreCase)");
            sb.AppendLine("            {");
            foreach (var entry in entries.Where(e => e.Inherited))
                sb.AppendLine($"                {StringLiteral(entry.Name)},");
            sb.AppendLine("            }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);");
        }

        private static void EmitSvgInitialValues(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        internal static readonly FrozenDictionary<string, string?> InitialValues =");
            sb.AppendLine("            new Dictionary<string, string?>(StringComparer.OrdinalIgnoreCase)");
            sb.AppendLine("            {");
            foreach (var entry in entries.Where(e => e.InitialValueKind != InitialValueKind.None))
            {
                var valueExpr = entry.InitialValueKind == InitialValueKind.Literal
                    ? StringLiteral(entry.InitialValueText!)
                    : entry.InitialValueText;
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = {valueExpr},");
            }
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);");
        }
