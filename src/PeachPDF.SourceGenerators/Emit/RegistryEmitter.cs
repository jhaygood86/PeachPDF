        public static string EmitHtmlRegistry(IReadOnlyList<PropertyEntry> entries)
        {
            var htmlEntries = entries.Where(e => e.Html is not null).ToList();
            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Generated by PeachPDF.SourceGenerators from css-properties.json. Do not edit by hand —");
            sb.AppendLine("// edit the JSON entry and rebuild. See CLAUDE.md's generator section.");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Frozen;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using PeachPDF.CSS;");
            sb.AppendLine("using PeachPDF.Html.Core.Dom;");
            sb.AppendLine("using PeachPDF.Html.Core.Entities;");
            sb.AppendLine("using PeachPDF.Html.Core.Parse;");
            sb.AppendLine();
            sb.AppendLine("namespace PeachPDF.Html.Core.Utils");
            sb.AppendLine("{");
            sb.AppendLine("    internal static partial class CssPropertyRegistry");
            sb.AppendLine("    {");

            foreach (var entry in htmlEntries)
                EmitHtmlEntryMethods(sb, entry);

            EmitHtmlSetterDictionary(sb, htmlEntries);
            EmitHtmlGetterDictionary(sb, htmlEntries);
            EmitHtmlValidatorDictionary(sb, htmlEntries);
            EmitHtmlSupportsValidatorDictionary(sb, htmlEntries);
            EmitInheritedProperties(sb, htmlEntries);
            EmitInitialValues(sb, htmlEntries);
            EmitSnapshotPropertyNames(sb, htmlEntries);
            EmitLogicalProperties(sb, htmlEntries);

            sb.AppendLine();
            sb.AppendLine("        internal static bool IsKnownProperty(string name) => _setters.ContainsKey(name);");
            sb.AppendLine();
            sb.AppendLine("        internal static bool IsInherited(string name) => InheritedProperties.Contains(name);");
            sb.AppendLine();
            sb.AppendLine("        internal static string? GetInitialValue(string name) => InitialValues.TryGetValue(name, out var v) ? v : null;");
            sb.AppendLine();
            sb.AppendLine("        internal static bool TrySet(CssValueParser parser, CssBox box, string name, string value) =>");
            sb.AppendLine("            _setters.TryGetValue(name, out var setter) && setter(parser, box, value);");
            sb.AppendLine();
            sb.AppendLine("        internal static string? Get(CssBox box, string name) =>");
            sb.AppendLine("            _getters.TryGetValue(name, out var getter) ? getter(box) : null;");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>Validation only — no box, no mutation, no side effects. The @supports render-layer oracle.</summary>");
            sb.AppendLine("        internal static bool SupportsDeclaration(CssValueParser parser, string name, string value) =>");
            sb.AppendLine("            _supportsValidators.TryGetValue(name, out var validator) && validator(parser, value);");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>Nominal-context overload for a caller (e.g. an @supports condition leaf) with no live parser/adapter of its own — grammar validation needs *an* adapter, not the document's real one.</summary>");
            sb.AppendLine("        internal static bool SupportsDeclaration(string name, string value) =>");
            sb.AppendLine("            SupportsDeclaration(new CssValueParser(new global::PeachPDF.Adapters.PdfSharpAdapter()), name, value);");

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static void EmitHtmlEntryMethods(StringBuilder sb, PropertyEntry entry)
        {
            var id = PascalCase(entry.Name);
            var html = entry.Html!;
            var isUnsupported = entry.CssDataTypes.Count == 1 && entry.CssDataTypes[0].Kind == DataTypeKind.Unsupported;

            sb.AppendLine();
            sb.AppendLine($"        // \"{entry.Name}\"");

            if (isUnsupported)
            {
                sb.AppendLine($"        private static bool Validate_{id}(CssValueParser parser, string value) => false;");
                sb.AppendLine($"        private static bool Supports_{id}(CssValueParser parser, string value) => false;");
                sb.AppendLine($"        private static bool Set_{id}(CssValueParser parser, CssBox box, string value) => false;");
                return;
            }

            var validatorExpr = html.CustomValidator is not null
                ? Substitute(html.CustomValidator, value: "value", parser: "parser")
                : ValidatorExpressionBuilder.BuildHtml(entry);

            sb.AppendLine($"        private static bool Validate_{id}(CssValueParser parser, string value) => {validatorExpr};");

            if (entry.SupportsCssDataTypes is not null)
            {
                var supportsExpr = ValidatorExpressionBuilder.BuildHtml(entry, entry.SupportsCssDataTypes,
                    entry.SupportsSupportedValues ?? entry.SupportedValues, entry.SupportsKeywordComparison ?? entry.KeywordComparison);
                sb.AppendLine($"        private static bool Supports_{id}(CssValueParser parser, string value) => {supportsExpr};");
            }
            else
            {
                sb.AppendLine($"        private static bool Supports_{id}(CssValueParser parser, string value) => Validate_{id}(parser, value);");
            }

            sb.AppendLine($"        private static bool Set_{id}(CssValueParser parser, CssBox box, string value)");
            sb.AppendLine("        {");
            sb.AppendLine($"            if (!Validate_{id}(parser, value)) return false;");
            sb.AppendLine($"            {BuildHtmlAssignment(entry)}");
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");

            if (html.HasGetter)
            {
                var getterExpr = html.GetterExpression is not null
                    ? Substitute(html.GetterExpression, box: "box")
                    : $"box.{html.PropertyPath}";
                sb.AppendLine($"        private static string? Get_{id}(CssBox box) => {getterExpr};");
            }
        }

        private static string BuildHtmlAssignment(PropertyEntry entry)
        {
            var html = entry.Html!;

            if (html.CustomSetter is not null)
                return Substitute(html.CustomSetter, value: "value", box: "box", parser: "parser");

            if (entry.CssDataTypes.Count == 1 && entry.CssDataTypes[0].Kind == DataTypeKind.EnumKeyword)
            {
                var dt = entry.CssDataTypes[0];
                return $"box.{html.PropertyPath} = CssProperty<{dt.EnumType}>.FromCssText(value, {dt.KeywordMap}, {dt.Fallback});";
            }

            if (entry.CssDataTypes.Count == 1 && entry.CssDataTypes[0].Kind == DataTypeKind.KeywordOrValue)
            {
                var dt = entry.CssDataTypes[0];
                var resolved = KeywordOrValueGrammar.Resolve(entry, dt);
                // A keyword-or-value property's html.valueComputation (e.g. word-spacing/letter-spacing's
                // "no-ems") must run on the raw authored text *before* FromCssText parses it - the box's
                // own generated property setter (StylePropertiesEmitter) no longer sees a string to run it
                // against once the property is typed, so this is the one place left with both the raw
                // string and a CssBox in scope. See StylePropertiesEmitter's doc comment.
                var rawValueExpr = html.ValueComputation switch
                {
                    null => "value",
                    "no-ems" => "box.NoEms(value)",
                    "font-size" => "box.ResolveFontSizeValueComputation(value)",
                    _ => throw new NotSupportedException(
                        $"\"{entry.Name}\" declares a keyword-or-value cssDataType with html.valueComputation " +
                        $"\"{html.ValueComputation}\", which RegistryEmitter does not implement."),
                };
                // Explicit type arguments: a method-group argument (int.TryParse) doesn't drive generic
                // inference for TValue the way a concrete delegate instance would.
                return $"box.{html.PropertyPath} = global::PeachPDF.CSS.CssKeywordOrValueParser.FromCssText<{dt.EnumType}, {resolved.CSharpType}>" +
                       $"({rawValueExpr}, {dt.KeywordMap}, {resolved.TryParseMethod}, {dt.Fallback});";
            }

            // A case-insensitively-matched keyword (plain "keyword", or the keyword side of a union like
            // "length" | "keyword") must be stored in its canonical (as-authored-in-JSON) casing, not the
            // raw input — every downstream layout/paint comparison against this field is an ordinal match
            // against a lowercase CssConstants.* literal, so an uncanonicalized "BLOCK" would validate but
            // then silently fail to match anything (issue #598). A non-keyword value (e.g. an actual length
            // for a union property) falls through the chain unchanged.
            var hasCaseInsensitiveKeyword = entry.KeywordComparison != KeywordComparison.Ordinal &&
                                             entry.CssDataTypes.Any(dt => dt.Kind == DataTypeKind.Keyword);
            if (hasCaseInsensitiveKeyword)
                return $"box.{html.PropertyPath} = {BuildKeywordCanonicalizationExpression(entry.SupportedValues, entry.KeywordComparison)};";

            return $"box.{html.PropertyPath} = value;";
        }

        /// <summary>Maps a case-insensitively-matched keyword back to its canonical spelling from
        /// <paramref name="supportedValues"/>; a value matching none of them (already validated as
        /// something else, e.g. a length) passes through unchanged.</summary>
        private static string BuildKeywordCanonicalizationExpression(IReadOnlyList<string>? supportedValues,
            KeywordComparison keywordComparison)
        {
            var values = supportedValues ?? Array.Empty<string>();
            if (values.Count == 0) return "value";

            var comparison = keywordComparison == KeywordComparison.OrdinalIgnoreCase
                ? "global::System.StringComparison.OrdinalIgnoreCase"
                : "global::System.StringComparison.InvariantCultureIgnoreCase";

            var chain = string.Concat(values.Select(v =>
                $"value.Equals({StringLiteral(v)}, {comparison}) ? {StringLiteral(v)} : "));
            return chain + "value";
        }

        private static void EmitHtmlSetterDictionary(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        private static readonly FrozenDictionary<string, Func<CssValueParser, CssBox, string, bool>> _setters =");
            sb.AppendLine("            new Dictionary<string, Func<CssValueParser, CssBox, string, bool>>(StringComparer.Ordinal)");
            sb.AppendLine("            {");
            foreach (var entry in entries)
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = Set_{PascalCase(entry.Name)},");
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.Ordinal);");
        }

        private static void EmitHtmlGetterDictionary(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        private static readonly FrozenDictionary<string, Func<CssBox, string?>> _getters =");
            sb.AppendLine("            new Dictionary<string, Func<CssBox, string?>>(StringComparer.Ordinal)");
            sb.AppendLine("            {");
            foreach (var entry in entries.Where(e => e.Html!.HasGetter))
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = Get_{PascalCase(entry.Name)},");
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.Ordinal);");
        }

        private static void EmitHtmlValidatorDictionary(StringBuilder sb, List<PropertyEntry> entries)
        {
            sb.AppendLine();
            sb.AppendLine("        private static readonly FrozenDictionary<string, Func<CssValueParser, string, bool>> _validators =");
            sb.AppendLine("            new Dictionary<string, Func<CssValueParser, string, bool>>(StringComparer.Ordinal)");
            sb.AppendLine("            {");
            foreach (var entry in entries)
                sb.AppendLine($"                [{StringLiteral(entry.Name)}] = Validate_{PascalCase(entry.Name)},");
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.Ordinal);");
        }

        private static void EmitHtmlSupportsValidatorDictionary(StringBuilder sb, List<PropertyEntry> entries)
