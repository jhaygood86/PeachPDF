    /// <summary>
    /// Emits <c>CssPropertyRegistry.g.cs</c> (namespace <c>PeachPDF.Html.Core.Utils</c>, matching
    /// <c>CssUtils</c>) and <c>SvgPropertyRegistry.g.cs</c> (namespace <c>PeachPDF.Svg</c>, matching
