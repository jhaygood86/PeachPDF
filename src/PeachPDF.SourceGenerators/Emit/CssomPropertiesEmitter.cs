using System.Collections.Generic;
using System.Linq;
using System.Text;
using PeachPDF.SourceGenerators.Model;

namespace PeachPDF.SourceGenerators.Emit
{
    /// <summary>
    /// Emits <c>CssomProperties.g.cs</c> (namespace <c>PeachBrackets.Css</c>): one CSS-OM <c>Property</c> class per
    /// entry carrying a <c>cssom</c> block, shaped exactly like the hand-written longhand classes (a static
    /// converter, the <c>PropertyFlags</c>, the <c>Converter</c> override), plus
    /// <c>PropertyFactory.RegisterGeneratedLonghands</c>, the registration of every one of them. Inheritance is the
    /// entry's own <c>inherited</c>, so the render-layer registry and the CSS-OM can no longer disagree about it.
    /// </summary>
    internal static class CssomPropertiesEmitter
    {
        public static string Emit(IReadOnlyList<PropertyEntry> entries)
        {
            var generated = entries.Where(e => e.Cssom is not null).ToList();

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Generated by PeachPDF.SourceGenerators from css-properties.json. Do not edit by hand -");
            sb.AppendLine("// edit the JSON entry (its \"cssom\" block) and rebuild. See CLAUDE.md's generator section.");
            sb.AppendLine("#nullable disable");
            sb.AppendLine();
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using static PeachBrackets.Css.Converters;");
            sb.AppendLine();
            sb.AppendLine("namespace PeachBrackets.Css");
            sb.AppendLine("{");

            foreach (var entry in generated)
            {
                var cssom = entry.Cssom!;
                var className = ClassNameOf(entry);
                sb.AppendLine($"    internal sealed class {className} : Property");
                sb.AppendLine("    {");
                sb.AppendLine("        private static readonly IValueConverter StyleConverter =");
                sb.AppendLine($"            ({cssom.Converter}).OrDefault();");
                sb.AppendLine();
                sb.AppendLine($"        internal {className}()");
                sb.AppendLine($"            : base({Literal(entry.Name)}, {FlagsOf(entry)})");
                sb.AppendLine("        {");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine("        internal override IValueConverter Converter => StyleConverter;");
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            sb.AppendLine("    internal sealed partial class PropertyFactory");
            sb.AppendLine("    {");
            sb.AppendLine("        private void RegisterGeneratedLonghands()");
            sb.AppendLine("        {");
            foreach (var entry in generated)
            {
                var cssom = entry.Cssom!;
                var args = Literal(entry.Name) + $", () => new {ClassNameOf(entry)}()";
                if (cssom.RegistryAnimatable || cssom.Font)
                    args += $", {Bool(cssom.RegistryAnimatable)}";
                if (cssom.Font)
                    args += ", true";
                sb.AppendLine($"            AddLonghand({args});");
            }
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string FlagsOf(PropertyEntry entry)
        {
            var cssom = entry.Cssom!;
            var flags = new List<string>();
            if (entry.Inherited) flags.Add("PropertyFlags.Inherited");
            if (cssom.Hashless) flags.Add("PropertyFlags.Hashless");
            if (cssom.Unitless) flags.Add("PropertyFlags.Unitless");
            if (cssom.Animatable) flags.Add("PropertyFlags.Animatable");
            return flags.Count == 0 ? "PropertyFlags.None" : string.Join(" | ", flags);
        }

        internal static string ClassNameOf(PropertyEntry entry)
        {
            if (entry.Cssom!.ClassName is { Length: > 0 } explicitName) return explicitName;

            var sb = new StringBuilder();
            var upper = true;
            foreach (var c in entry.Name)
            {
                if (c == '-') { upper = true; continue; }
                sb.Append(upper ? char.ToUpperInvariant(c) : c);
                upper = false;
            }
            return sb.Append("Property").ToString();
        }

        private static string Bool(bool value) => value ? "true" : "false";

        private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }
}
